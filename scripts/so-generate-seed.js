#!/usr/bin/env node
'use strict';
// Generates supabase/smooth_operators_seed.sql from api/_lib/so/content.js.
// Usage: node scripts/so-generate-seed.js > supabase/smooth_operators_seed.sql
//
// The seed creates the default cohort with the brief's RECOMMENDED defaults
// (owner must confirm them in admin before sales), the three weeks, the 21
// provisional days as DRAFT + sample, and suggested FAQs as DRAFT.
// It never overwrites rows that already exist.

const { WEEKS, PROVISIONAL_DAYS, FAQ_SEED } = require('../api/_lib/so/content');

const q = s => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);

const out = [];
out.push(`-- Smooth Operators — seed data (generated by scripts/so-generate-seed.js; do not edit by hand)
-- Run after supabase/smooth_operators.sql. Safe to re-run: existing rows are left untouched.
--
-- Cohort values are the build brief's RECOMMENDED DEFAULTS, not owner-confirmed:
--   start 2027-01-01, 21 days, America/Los_Angeles, days unlock 00:00 cohort time,
--   introductions open and intro price ends 2026-12-01 00:00 America/Los_Angeles (08:00 UTC),
--   $999 intro / $1,497 regular, sales disabled, access policy unset.
-- The 21 days below are PROVISIONAL draft curriculum (is_sample = true, status = draft).

insert into so_cohorts (slug, name, start_date, days_count, timezone, unlock_time, intro_opens_at,
  regular_price_cents, intro_price_cents, price_cutoff_at, checkout_ttl_minutes, is_default)
values ('2027-01', 'Smooth Operators', '2027-01-01', 21, 'America/Los_Angeles', '00:00',
  '2026-12-01T08:00:00Z', 149700, 99900, '2026-12-01T08:00:00Z', 60, true)
on conflict (slug) do nothing;
`);

for (const w of WEEKS) {
  out.push(`insert into so_weeks (cohort_id, week_number, pillar, title, assignment)
select id, ${w.week_number}, ${q(w.pillar)}, ${q(w.title)}, ${q(w.assignment)} from so_cohorts where slug = '2027-01'
on conflict do nothing;`);
}
out.push('');

PROVISIONAL_DAYS.forEach(([title, reflection, action], i) => {
  const n = i + 1;
  const purpose = n === 4 ? 'Give people a way to make decisions without you.' : null;
  out.push(`insert into so_days (cohort_id, day_number, title, preview_summary, purpose, reflection_prompt, action_title, action_body, status, is_sample)
select id, ${n}, ${q(title)}, ${q(action)}, ${q(purpose)}, ${q(reflection)}, ${q('Today’s action')}, ${q(action)}, 'draft', true from so_cohorts where slug = '2027-01'
on conflict (cohort_id, day_number) do nothing;`);
});
out.push('');

out.push(`do $$ begin
  if not exists (select 1 from so_faqs) then`);
FAQ_SEED.forEach(([question, answer], i) => {
  out.push(`    insert into so_faqs (cohort_id, question, answer, sort, audience, status)
    select id, ${q(question)}, ${q(answer)}, ${(i + 1) * 10}, 'both', 'draft' from so_cohorts where slug = '2027-01';`);
});
out.push(`  end if;
end $$;
`);

process.stdout.write(out.join('\n') + '\n');
