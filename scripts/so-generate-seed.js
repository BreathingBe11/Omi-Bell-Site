#!/usr/bin/env node
'use strict';
// Generates supabase/smooth_operators_seed.sql from api/_lib/so/content.js.
// Usage: node scripts/so-generate-seed.js > supabase/smooth_operators_seed.sql
//
// The seed creates the default cohort with the brief's RECOMMENDED defaults
// (owner must confirm them in admin before sales), the three weeks, the 21
// provisional days as DRAFT + sample, and suggested FAQs as DRAFT.
// It never overwrites rows that already exist.

const { WEEKS, PROVISIONAL_DAYS, FAQ_SEED, RETIRED_FAQS, CONFIRMED_KEYS, SITE_CONTENT } = require('../api/_lib/so/content');

const CALL_DESC = 'Group coaching on Zoom, led by Omi Bell. A participant brings a business challenge they’re working through that week, the group contributes ideas and experience, and Omi guides the conversation toward practical next steps. The recording is available in the platform afterward.';
const q = s => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);

const out = [];
out.push(`-- Smooth Operators — seed data (generated by scripts/so-generate-seed.js; do not edit by hand)
-- Run after supabase/smooth_operators.sql. Safe to re-run: existing rows are left untouched.
--
-- Cohort values are the build brief's RECOMMENDED DEFAULTS, not owner-confirmed:
--   start 2027-01-04 (Jan 4–24), 21 days, America/Los_Angeles, days unlock 00:00 cohort time,
--   introductions open and intro price ends 2026-12-01 00:00 America/Los_Angeles (08:00 UTC),
--   $997 intro / $1,497 regular, sales disabled, 12 months of access (Jan 4, 2027 – Jan 3, 2028 Pacific).
-- The 21 days below are PROVISIONAL draft curriculum (is_sample = true, status = draft).

insert into so_cohorts (slug, name, start_date, days_count, timezone, unlock_time, intro_opens_at,
  regular_price_cents, intro_price_cents, price_cutoff_at, checkout_ttl_minutes, access_policy, access_ends_at, is_default)
values ('2027-01', 'Smooth Operators', '2027-01-04', 21, 'America/Los_Angeles', '00:00',
  '2026-12-01T08:00:00Z', 149700, 99700, '2026-12-01T08:00:00Z', 60, 'until_date', '2028-01-04T08:00:00Z', true)
on conflict (slug) do nothing;
`);

for (const w of WEEKS) {
  out.push(`insert into so_weeks (cohort_id, week_number, pillar, title, assignment)
select id, ${w.week_number}, ${q(w.pillar)}, ${q(w.title)}, ${q(w.assignment)} from so_cohorts where slug = '2027-01'
on conflict do nothing;`);
}
out.push('');

PROVISIONAL_DAYS.forEach(([title, reflection, action], i) => {
  const n = i + 1;
  const purpose = n === 4 ? 'Give people a way to make decisions without you.' : null;
  out.push(`insert into so_days (cohort_id, day_number, title, preview_summary, purpose, reflection_prompt, action_title, action_body, status, is_sample)
select id, ${n}, ${q(title)}, ${q(action)}, ${q(purpose)}, ${q(reflection)}, ${q('Today’s action')}, ${q(action)}, 'draft', true from so_cohorts where slug = '2027-01'
on conflict (cohort_id, day_number) do nothing;`);
});
out.push('');

// Solutions Seat on Zoom: Wednesdays Jan 6, 13, 20, 2027, 1–2 pm PST (21:00 UTC), one hour each.
// Meeting links are added in admin -> Solutions Seat. Never duplicated on re-run.
[['2027-01-06', 1], ['2027-01-13', 2], ['2027-01-20', 3]].forEach(([d, w]) => {
  out.push(`insert into so_calls (cohort_id, title, description, starts_at, duration_minutes, status)
select id, ${q(`Solutions Seat · Week ${w}`)}, ${q(CALL_DESC)}, '${d}T21:00:00Z', 60, 'scheduled'
from so_cohorts c where slug = '2027-01'
  and not exists (select 1 from so_calls x where x.cohort_id = c.id and x.starts_at = '${d}T21:00:00Z');`);
});
out.push('');

// v3 (Nov 2026), applied once: no fit check or review; owner-confirmed copy,
// FAQ, access period and call descriptions. Marked in the audit log so later
// edits made in admin are never overwritten by re-running this file.
const content = key => SITE_CONTENT.find(c => c.key === key).default;
out.push(`do $$ begin
  if not exists (select 1 from so_admin_audit_log where action = 'migration:v3-direct-enrollment') then
    delete from so_faqs where question in (${RETIRED_FAQS.map(q).join(', ')});`);
FAQ_SEED.forEach(([question, answer], i) => {
  out.push(`    insert into so_faqs (cohort_id, question, answer, sort, audience, status)
    select null, ${q(question)}, ${q(answer)}, ${(i + 1) * 10}, 'both', 'published'
    where not exists (select 1 from so_faqs where question = ${q(question)});`);
});
for (const key of CONFIRMED_KEYS) {
  out.push(`    insert into so_site_content (key, value, status, updated_by) values (${q(key)}, ${q(content(key))}, 'published', 'migration')
    on conflict (key) do update set value = excluded.value, status = 'published', updated_at = now(), updated_by = 'migration';`);
}
out.push(`    update so_cohorts set access_policy = 'until_date', access_ends_at = '2028-01-04T08:00:00Z' where slug = '2027-01';
    update so_calls set description = ${q(CALL_DESC)}, duration_minutes = 60
      where cohort_id = (select id from so_cohorts where slug = '2027-01') and starts_at in ('2027-01-06T21:00:00Z', '2027-01-13T21:00:00Z', '2027-01-20T21:00:00Z');
    insert into so_admin_audit_log (actor, action, entity) values ('migration', 'migration:v3-direct-enrollment', 'site');
  end if;
end $$;
`);

// v4 (Nov 2026), applied once: $997 introductory price; republish the Terms
// and Privacy Policy (checkout without signing in, one reminder email).
out.push(`do $$ begin
  if not exists (select 1 from so_admin_audit_log where action = 'migration:v4-open-checkout') then
    update so_cohorts set intro_price_cents = 99700 where slug = '2027-01' and intro_price_cents = 99900;`);
for (const key of ['legal.terms', 'legal.privacy']) {
  out.push(`    insert into so_site_content (key, value, status, updated_by) values (${q(key)}, ${q(content(key))}, 'published', 'migration')
    on conflict (key) do update set value = excluded.value, status = 'published', updated_at = now(), updated_by = 'migration';`);
}
out.push(`    insert into so_admin_audit_log (actor, action, entity) values ('migration', 'migration:v4-open-checkout', 'site');
  end if;
end $$;
`);

process.stdout.write(out.join('\n') + '\n');
